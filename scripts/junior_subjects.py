def seed(db):
    rows = []
    for grade, term, subject in db.execute("SELECT DISTINCT grade,term,subject FROM book WHERE subject NOT IN ('chinese','english','math') ORDER BY grade,term,subject"):
        key = subject + str(grade) + str(term)
        text = ACTIVITIES.get(key) or next((v for k,v in ACTIVITIES.items() if k in subject), None)
        # Prefer a specific art discipline over the general arts course.
        for discipline in ("舞蹈", "音乐", "影视", "戏剧", "美术"):
            if discipline in subject:
                text = ACTIVITIES[discipline]
        if not text:
            raise ValueError(f"Missing library activity: {grade}, {term}, {subject}")
        title, prompt, correct, wrong1, wrong2, explain = text.split("|")
        options=[correct,wrong1,wrong2]
        random.Random(f"{grade}-{term}-{subject}").shuffle(options)
        scenes=[{"label":"想一想","say":prompt,"items":[]},{"label":"观察要点","say":explain,"items":[title]}]
        rows.append((f"ext-{grade}-{term}-{subject}",grade,term,subject,"学科探究",title,json.dumps(scenes,ensure_ascii=False),prompt,json.dumps(options,ensure_ascii=False),options.index(correct),explain,None))
    db.execute("DELETE FROM study_card WHERE id LIKE 'ext-%'")
    db.executemany("INSERT INTO study_card VALUES(?,?,?,?,?,?,?,?,?,?,?,?)", rows)
